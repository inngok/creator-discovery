"""Sync the backend-owned contract into this crawler checkout; --check detects drift."""
import argparse
import json
from pathlib import Path


def migration(contract):
    rows = []
    seen = set()
    for label in [*contract["categories"], *contract["niches"]]:
        for alias in dict.fromkeys([label["code"], *label["aliases"]]):
            if alias.lower() in seen:
                continue
            seen.add(alias.lower())
            quote = lambda value: "'" + value.replace("'", "''") + "'"
            rows.append("    (" + ", ".join(map(quote, [alias.lower(), label["code"], label.get("category", label["code"])])) + ")")
    return """-- Generated by scripts/sync_discovery_contract.py from creator-discovery-v1.json.
-- Canonicalize observed labels only; never infer a label from crawl configuration.
WITH aliases(alias, code, parent) AS (VALUES
""" + ",\n".join(rows) + """
), classified AS (
    SELECT m.id, COALESCE(category_alias.parent, NULLIF(BTRIM(m.category), ''), 'UNKNOWN') AS category,
           COALESCE(whole.code, m.niche) AS niche,
           ARRAY(SELECT DISTINCT a.parent FROM unnest(
               CASE WHEN whole.code IS NOT NULL THEN ARRAY[whole.code]
                    ELSE string_to_array(COALESCE(m.niche, ''), ',') END) part
               JOIN aliases a ON a.alias=LOWER(BTRIM(part))) AS parents
    FROM public_creator_metric m
    LEFT JOIN aliases category_alias ON category_alias.alias=LOWER(BTRIM(m.category))
    LEFT JOIN aliases whole ON whole.alias=LOWER(BTRIM(m.niche))
    WHERE m.quality_reviewed_at IS NULL
)
UPDATE public_creator_metric m
SET category=CASE WHEN cardinality(c.parents)=1 THEN c.parents[1]
                  WHEN cardinality(c.parents)>1 AND NOT (c.category=ANY(c.parents)) THEN 'UNKNOWN'
                  ELSE c.category END,
    niche=c.niche
FROM classified c WHERE m.id=c.id;
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend-root", required=True, type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    crawler = Path(__file__).resolve().parents[1]
    backend = args.backend_root.resolve()
    source = backend / "src/main/resources/contracts/creator-discovery-v1.json"
    content = source.read_bytes()
    artifacts = {
        crawler / "app/contracts/creator-discovery-v1.json": content,
        backend / "src/main/resources/db/migration/V57__align_observed_discovery_categories.sql":
            migration(json.loads(content)).encode("utf-8"),
    }
    for path, expected in artifacts.items():
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                raise SystemExit(f"Discovery contract drift: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    print("Discovery contract artifacts match" if args.check else "Discovery contract artifacts synchronized")


if __name__ == "__main__":
    main()
